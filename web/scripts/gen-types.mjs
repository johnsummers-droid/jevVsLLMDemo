// Generate src/types/generated.ts from ../shared/schema/*.schema.json (plan1.txt T6).
//   npm run gen:types
// The schema files are written by server/scripts/export_schema.py. Each is self-contained, so
// shared $defs repeat across files; they are merged here and must be identical.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const schemaDir = join(here, '../../shared/schema')
const outFile = join(here, '../src/types/generated.ts')

const defs = {}
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith('.schema.json')).sort()) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), 'utf8'))
  for (const [name, def] of Object.entries(schema.$defs ?? {})) {
    if (name in defs && JSON.stringify(defs[name]) !== JSON.stringify(def)) {
      throw new Error(`$defs.${name} differs between schema files (seen again in ${file})`)
    }
    defs[name] = def
  }
}

// The generator reads draft-07 tuples (`items: [...]`), not 2020-12 `prefixItems`.
function adapt(node) {
  if (Array.isArray(node)) return node.map(adapt)
  if (node === null || typeof node !== 'object') return node
  const out = {}
  for (const [key, value] of Object.entries(node)) {
    if (key === 'prefixItems') out.items = adapt(value)
    else out[key] = adapt(value)
  }
  return out
}

const sortedDefs = Object.fromEntries(Object.keys(defs).sort().map((k) => [k, adapt(defs[k])]))
const root = {
  title: 'GeneratedRoot',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(sortedDefs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  $defs: sortedDefs,
}

let ts = await compile(root, 'GeneratedRoot', {
  additionalProperties: false,
  bannerComment:
    '/* GENERATED by web/scripts/gen-types.mjs from shared/schema. DO NOT EDIT.\n' +
    ' * Regenerate: (server) .venv/bin/python scripts/export_schema.py, then (web) npm run gen:types */',
  declareExternallyReferenced: true,
  ignoreMinAndMaxItems: true,
  format: true,
  style: { semi: false, singleQuote: true },
})

// Drop the synthetic root interface; only the $defs are wanted.
ts = ts.replace(/export interface GeneratedRoot \{[\s\S]*?\n\}\n\n?/, '')
writeFileSync(outFile, ts)
console.log(`wrote ${outFile} (${Object.keys(sortedDefs).length} types)`)
