"""Export server-computed reference data for the web tests (plan1.txt T7).

    .venv/bin/python scripts/export_web_fixtures.py          # write the files
    .venv/bin/python scripts/export_web_fixtures.py --check  # exit 1 if they are stale

  - shared/fixtures/catalog.json: the GET /api/catalog response, so web tests run without a server.
  - shared/fixtures/expanded-outputs.json: registry.expand_outputs for every node of the default,
    weak and strong graphs; web/src/lib/graphMapping.ts's expandOutputs must produce the same ports.
"""

import argparse
import json
import sys
from pathlib import Path

from app.api.catalog import CatalogResponse
from app.catalog.registry import catalog, expand_outputs, get_definition
from app.models import Graph

FIXTURES = Path(__file__).resolve().parents[2] / "shared" / "fixtures"
GRAPHS = ("default", "weak", "strong")


def _dump(data: object) -> str:
    return json.dumps(data, indent=2) + "\n"


def render_catalog() -> str:
    return _dump(CatalogResponse(nodes=catalog()).model_dump(mode="json", by_alias=True))


def render_expanded_outputs() -> str:
    out: dict[str, dict[str, list]] = {}
    for name in GRAPHS:
        graph = Graph.model_validate_json((FIXTURES / "graphs" / f"{name}.json").read_text())
        out[name] = {
            node.id: [
                port.model_dump(mode="json", by_alias=True)
                for port in expand_outputs(get_definition(node.type), node.params)
            ]
            for node in graph.nodes
        }
    return _dump({
        "description": "registry.expand_outputs per node of each reference graph. Generated by "
        "server/scripts/export_web_fixtures.py; do not edit.",
        "graphs": out,
    })


OUTPUTS = {
    "catalog.json": render_catalog,
    "expanded-outputs.json": render_expanded_outputs,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the fixtures are stale")
    args = parser.parse_args()

    stale = []
    for name, render in OUTPUTS.items():
        path = FIXTURES / name
        text = render()
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print(f"stale fixtures: {', '.join(stale)}; run scripts/export_web_fixtures.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
